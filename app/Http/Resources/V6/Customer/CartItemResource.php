<?php

namespace App\Http\Resources\V6\Customer;

use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\JsonResource;

class CartItemResource extends JsonResource
{
    public function toArray(Request $request): array
    {
        return [
            'id' => $this->id,
            'customer_id' => $this->customer_id,
            'cart_group_id' => $this->cart_group_id,
            'product_id' => $this->product_id,
            'product_type' => $this->product_type,
            'digital_product_type' => $this->digital_product_type,
            'color' => $this->color,
            'choices' => $this->choices,
            'variations' => $this->variations,
            'variant' => $this->variant,
            'quantity' => $this->quantity,
            'price' => $this->price,
            'tax' => $this->tax,
            'discount' => $this->discount,
            'tax_model' => $this->tax_model,
            'is_checked' => $this->is_checked,
            'slug' => $this->slug,
            'name' => $this->name,
            'thumbnail' => $this->thumbnail,
            'seller_id' => $this->seller_id,
            'seller_is' => $this->seller_is,
            'shop_info' => $this->shop_info,
            'shipping_cost' => $this->shipping_cost,
            'shipping_type' => $this->shipping_type,
            'is_guest' => $this->is_guest,
            'created_at' => $this->created_at,
            'updated_at' => $this->updated_at,
            'applied_tax' => $this->when($this->hasComputedValue(key: 'applied_tax'), fn () => $this->applied_tax),
            'shipping_cost_tax' => $this->when($this->hasComputedValue(key: 'shipping_cost_tax'), fn () => $this->shipping_cost_tax),
            'is_product_available' => $this->is_product_available,
            'applied_tax_type' => $this->applied_tax_type,
            'minimum_order_amount_info' => $this->minimum_order_amount_info,
            'free_delivery_order_amount' => $this->free_delivery_order_amount,
            'shop' => $this->whenLoaded('shop', fn () => $this->shop === null ? null : [
                'id' => $this->shop->id,
                'seller_id' => $this->shop->seller_id,
                'author_type' => $this->shop->author_type,
                'name' => $this->shop->name,
                'slug' => $this->shop->slug,
                'address' => $this->shop->address,
                'contact' => $this->shop->contact,
                'image' => $this->shop->image,
                'image_full_url' => $this->shop->image_full_url,
                'banner' => $this->shop->banner,
                'banner_full_url' => $this->shop->banner_full_url,
                'bottom_banner' => $this->shop->bottom_banner,
                'bottom_banner_full_url' => $this->shop->bottom_banner_full_url,
                'offer_banner' => $this->shop->offer_banner,
                'offer_banner_full_url' => $this->shop->offer_banner_full_url,
                'vacation_start_date' => $this->shop->vacation_start_date,
                'vacation_end_date' => $this->shop->vacation_end_date,
                'vacation_duration_type' => $this->shop->vacation_duration_type,
                'vacation_note' => $this->shop->vacation_note,
                'vacation_status' => $this->shop->vacation_status,
                'vacation_modules' => $this->shop->vacation_modules,
                'temporary_close' => $this->shop->temporary_close,
                'created_at' => $this->shop->created_at,
                'updated_at' => $this->shop->updated_at,
            ]),
            'product' => $this->whenLoaded('product', fn () => $this->product === null ? null : [
                'id' => $this->product->id,
                'added_by' => $this->product->added_by,
                'user_id' => $this->product->user_id,
                'shop_id' => $this->product->shop_id,
                'name' => $this->product->name,
                'slug' => $this->product->slug,
                'product_type' => $this->product->product_type,
                'category_ids' => $this->product->category_ids,
                'category_id' => $this->product->category_id,
                'sub_category_id' => $this->product->sub_category_id,
                'sub_sub_category_id' => $this->product->sub_sub_category_id,
                'brand_id' => $this->product->brand_id,
                'unit' => $this->product->unit,
                'images' => $this->product->images,
                'images_full_url' => $this->product->images_full_url,
                'thumbnail' => $this->product->thumbnail,
                'thumbnail_full_url' => $this->product->thumbnail_full_url,
                'preview_file_full_url' => $this->product->preview_file_full_url,
                'digital_file_ready_full_url' => $this->product->digital_file_ready_full_url,
                'colors' => $this->product->colors,
                'color_images_full_url' => $this->product->color_images_full_url,
                'attributes' => $this->product->attributes,
                'choice_options' => $this->product->choice_options,
                'unit_price' => $this->product->unit_price,
                'tax' => $this->product->tax,
                'tax_type' => $this->product->tax_type,
                'tax_model' => $this->product->tax_model,
                'discount' => $this->product->discount,
                'discount_type' => $this->product->discount_type,
                'current_stock' => $this->product->current_stock,
                'total_current_stock' => $this->product->total_current_stock,
                'minimum_order_qty' => $this->product->minimum_order_qty,
                'details' => $this->product->details,
                'status' => $this->product->status,
                'featured_status' => $this->product->featured_status,
                'shipping_cost' => $this->product->shipping_cost,
                'multiply_qty' => $this->product->multiply_qty,
                'code' => $this->product->code,
                'is_shop_temporary_close' => $this->product->is_shop_temporary_close,
                'created_at' => $this->product->created_at,
                'updated_at' => $this->product->updated_at,
                'clearance_sale' => $this->product->relationLoaded('clearanceSale') && $this->product->clearanceSale !== null ? [
                    'id' => $this->product->clearanceSale->id,
                    'product_id' => $this->product->clearanceSale->product_id,
                    'is_active' => $this->product->clearanceSale->is_active,
                    'discount_type' => $this->product->clearanceSale->discount_type,
                    'discount_amount' => $this->product->clearanceSale->discount_amount,
                ] : null,
            ]),
        ];
    }

    private function hasComputedValue(string $key): bool
    {
        return array_key_exists($key, $this->resource->getAttributes());
    }
}
